// Writes extension/stylesheet.css from tools/stylesheet.template.css.
//
//   gjs -m tools/build-stylesheet.js
//
// St has no CSS custom properties, so the part below the "themed" marker is
// written once per colour style and scheme, with $role placeholders taken
// from extension/lib/palettes.js and ".halo-scheme" made specific, e.g.
// ".halo-scheme-violet-dark". Switching a colour swaps one class.
import Gio from 'gi://Gio';
import GLib from 'gi://GLib';

import {COLOURS, palette, rgba, warn} from '../extension/lib/shared/palettes.js';

const root = GLib.path_get_dirname(GLib.path_get_dirname(GLib.filename_from_uri(import.meta.url)[0]));
const read = path => new TextDecoder().decode(Gio.File.new_for_path(`${root}/${path}`).load_contents(null)[1]);

const template = read('tools/stylesheet.template.css');
const [shared, themed] = template.split('/* themed */');

// "$role" is the role's colour, "$role@78" the same at 78 % opacity.
function expand(css, roles, scheme) {
    return css.replace(/\$([a-zA-Z]+)(?:@(\d+))?/g, (_, name, alpha) => {
        let hex;
        if (name === 'warn')
            hex = warn[scheme];
        else if (name === 'onWarn')
            hex = warn.on;
        else if (name in roles)
            hex = roles[name];
        else
            throw new Error(`Unknown role in the template: ${name}`);
        return alpha ? rgba(hex, Number(alpha) / 100) : hex;
    });
}

const sheets = [];
for (const colour of COLOURS) {
    for (const scheme of ['light', 'dark']) {
        const css = themed.replace(/\.halo-scheme\b/g, `.halo-scheme-${colour}-${scheme}`);
        sheets.push(expand(css, palette(colour, scheme), scheme).trim());
    }
}
const header = '/* Generated by tools/build-stylesheet.js from tools/stylesheet.template.css. Do not edit. */\n';
GLib.file_set_contents(`${root}/extension/stylesheet.css`, `${header}\n${shared.trim()}\n\n${sheets.join('\n\n')}\n`);
print('Wrote extension/stylesheet.css');
